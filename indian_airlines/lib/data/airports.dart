  static Airport? findByCode(String code) {
    try {
      return airports.firstWhere((a) => a.code.toUpperCase() == code.toUpperCase());
    } catch (_) {
      return null;
    }
  }

  static List<Airport> search(String query) {
    if (query.trim().isEmpty) return airports;
    final q = query.toLowerCase().trim();
    return airports.where((a) {
      return a.code.toLowerCase().contains(q) ||
          a.city.toLowerCase().contains(q) ||
          a.name.toLowerCase().contains(q) ||
          a.country.toLowerCase().contains(q);
    }).toList();
  }
